"""Worked examples of the injury adjustment, rebuilt game by game from existing project data.

    python -m src.analysis.injury_method_example

Picks episodes from `playing_time_injury_adjusted_episodes.csv` by fixed rules, rebuilds each one's receiving-club
league games, appearances and injury spells from the snapshot and the normalised Kaggle injury file, applies the same
`game_flags` rule as the analysis, and checks that every count and share equals the saved episode row. No estimation;
no new data. Writes one new file.
"""
from __future__ import annotations

import json

import pandas as pd

from . import playing_time_injury_adjusted as ia
from .loan_episodes import ROOT

OUT = ROOT / "data" / "outputs" / "rebuild"
EXAMPLE_MD = OUT / "injury_method_example.md"
EPISODES = ia.EPISODES_CSV
JOIN_EPISODES = OUT / "playing_time_join_episodes.csv"

RULES = [
    ("A loan with a multi-game injury (England)",
     "usable loan in GB1; one injury spell; 3–6 games removed; no appearance inside the spell; current share > 0.3; "
     "latest arrival season, then lowest event id",
     lambda E: E[E.kind.eq("loan") & E.receiving_league.eq("GB1") & E.injury_spell_count.eq(1)
                 & E.confirmed_injury_games.between(3, 6) & E.appearance_conflicts.eq(0) & E.current_share.gt(0.3)]),
    ("An appearance inside an injury spell",
     "usable episode with at least one appearance inside a spell and at least 2 games removed; current share > 0.2; "
     "latest arrival season, then lowest event id",
     lambda E: E[E.appearance_conflicts.ge(1) & E.confirmed_injury_games.ge(2) & E.current_share.gt(0.2)]),
    ("A permanent signing with a multi-game injury",
     "usable permanent move outside GB1; one injury spell; 2–6 games removed; no appearance inside the spell; "
     "current share > 0.3; latest arrival season, then lowest event id",
     lambda E: E[E.kind.eq("permanent") & E.receiving_league.ne("GB1") & E.injury_spell_count.eq(1)
                 & E.confirmed_injury_games.between(2, 6) & E.appearance_conflicts.eq(0) & E.current_share.gt(0.3)]),
]


def pick(E: pd.DataFrame) -> list[tuple[str, str, pd.Series]]:
    U = E[E.usable]
    out = []
    for title, rule, f in RULES:
        c = f(U).sort_values(["arrival_season", "event_id"], ascending=[False, True])
        out.append((title, rule, c.iloc[0]))
    return out


def rebuild(ep: pd.Series, J: pd.Series, INJ: pd.DataFrame, con) -> dict:
    pid, club, season = int(ep.player_id), int(J.b_club_id), int(ep.arrival_season)
    ws, we = pd.Timestamp(ep.window_start), pd.Timestamp(ep.window_end)
    g = con.sql(f"""select game_id, date, home_club_id, away_club_id, home_club_name, away_club_name
                    from games where competition_type = 'domestic_league' and cast(season as int) = {season}
                    and {club} in (home_club_id, away_club_id) order by date""").df()
    g["date"] = pd.to_datetime(g.date)
    g = g[(g.date >= ws) & (g.date <= we)].copy()
    g["opponent"] = [a if h == club else hn for h, hn, a in zip(g.home_club_id, g.home_club_name, g.away_club_name)]
    g["venue"] = ["home" if h == club else "away" for h in g.home_club_id]
    ap = con.sql(f"""select cast(game_id as varchar) game_id, minutes_played from appearances
                     where player_id = {pid}""").df()
    g = g.merge(ap, on="game_id", how="left")
    g["played"] = g.minutes_played.notna()
    W = g.assign(event_id=ep.event_id, player_id=pid)
    Sp = ia.spells(INJ, "primary")
    Sp = Sp[Sp.player_id == pid]
    G, _ = ia.game_flags(W, Sp)
    g = g.merge(G[["game_id", "covering_spells", "spell_covers", "medical_unavailable", "appearance_conflict"]], on="game_id")
    rows = INJ[(INJ.player_id == pid) & INJ.from_date.notna()
               & (INJ.from_date <= we) & (INJ.end_date.fillna(INJ.from_date) >= ws)]
    minutes = int(g.minutes_played.fillna(0).sum())
    n, k = len(g), int(g.medical_unavailable.sum())
    rec = {"player_id": pid, "player_name": J.player_name, "kind": ep.kind, "from_club": J.a_club, "to_club": J.b_club,
           "league": ep.receiving_league, "season": season, "move_date": str(J.move_date), "window_start": str(ws.date()),
           "window_end": str(we.date()), "games": n, "removed": k, "fit_games": n - k, "minutes": minutes,
           "current_share": minutes / (90 * n), "fit_share": minutes / (90 * (n - k)),
           "conflicts": int(g.appearance_conflict.sum()), "games_table": g, "spell_rows": rows}
    assert n == ep.available_games_current and k == ep.confirmed_injury_games and rec["conflicts"] == ep.appearance_conflicts
    assert abs(rec["current_share"] - ep.current_share) < 1e-9 and abs(rec["fit_share"] - ep.fit_adjusted_share) < 1e-9
    return rec


def render(examples: list[tuple[str, str, dict]]) -> str:
    W = ["# The injury adjustment, worked through real episodes", "",
         "*Generated by `python -m src.analysis.injury_method_example` from existing project data only: the episode "
         f"rows in `{EPISODES.name}`, the snapshot's league games and appearances, and the normalised Kaggle injury "
         "file. Every count and share below is rebuilt game by game and checked against the saved episode row.*", "",
         "**The rule.** A receiving-club league game leaves the denominator only if a recorded injury or illness spell "
         "covers its date (start and end dates inclusive) and the player did not appear in it. An appearance always wins. "
         "The numerator, his league minutes, never changes.", ""]
    for i, (title, rule, r) in enumerate(examples, 1):
        g = r["games_table"]
        W += [f"## {i}. {title}", "", f"*Selected by rule: {rule}.*", ""]
        W += [f"- **Player:** {r['player_name']} (Transfermarkt id {r['player_id']})",
              f"- **Move:** {r['kind']}, {r['from_club']} → {r['to_club']} ({r['league']}), dated {r['move_date']}",
              f"- **Observation window:** {r['window_start']} to {r['window_end']}",
              f"- **League games in the current denominator:** {r['games']}; league minutes played: {r['minutes']:,}", ""]
        W += ["**Injury rows from the source that touch the window:**", ""]
        W += ["| Injury (source label) | From | Until | Days | Games missed (source) | Counts as medical? |",
              "| --- | --- | --- | ---: | ---: | --- |"]
        for s in r["spell_rows"].itertuples():
            W += [f"| {s.injury_reason_raw} | {s.from_date.date()} | "
                  f"{s.end_date.date() if pd.notna(s.end_date) else 'open'} | {'' if pd.isna(s.days_missed) else int(s.days_missed)} | "
                  f"{'' if pd.isna(s.games_missed) else int(s.games_missed)} | "
                  f"{'yes' if s.counts_primary else 'no (' + s.category + ')'} |"]
        spell = g[g.spell_covers]
        W += ["", "**League games that fall inside a spell:**", "",
              "| Date | Opponent | Venue | Played? | Minutes | Result for the denominator |", "| --- | --- | --- | --- | ---: | --- |"]
        for x in spell.itertuples():
            W += [f"| {x.date.date()} | {x.opponent} | {x.venue} | {'yes' if x.played else 'no'} | "
                  f"{'' if pd.isna(x.minutes_played) else int(x.minutes_played)} | "
                  f"{'kept: he appeared, so he was available' if x.played else 'removed: confirmed injury, did not appear'} |"]
        W += ["", f"- **Games removed:** {r['removed']} of {r['games']}"
              + (f"; {r['conflicts']} game(s) inside a spell stay because he appeared" if r["conflicts"] else ""),
              f"- **Current share:** {r['minutes']:,} / (90 × {r['games']}) = **{r['current_share']:.3f}**",
              f"- **Injury-adjusted share:** {r['minutes']:,} / (90 × {r['fit_games']}) = **{r['fit_share']:.3f}**", ""]
    return "\n".join(W)


def main() -> list:
    import duckdb
    from ..config import DEFAULT_DATABASE
    from .club_geography_v2 import CANONICAL_CSV, STAGE1C_SHA256, sha256

    assert sha256(CANONICAL_CSV) == STAGE1C_SHA256
    E = pd.read_csv(EPISODES)
    J = pd.read_csv(JOIN_EPISODES, usecols=["event_id", "player_name", "a_club", "b_club", "b_club_id", "move_date"]).set_index("event_id")
    INJ = pd.read_csv(ia.PROCESSED, parse_dates=["from_date", "end_date"])
    con = duckdb.connect(str(DEFAULT_DATABASE), read_only=True)
    try:
        ex = [(t, rule, rebuild(ep, J.loc[ep.event_id], INJ, con)) for t, rule, ep in pick(E)]
    finally:
        con.close()
    assert any(r["removed"] >= 2 for _, _, r in ex) and any(r["conflicts"] >= 1 for _, _, r in ex)
    EXAMPLE_MD.write_text(render(ex))
    for t, _, r in ex:
        print(f"{t}: {r['player_name']} ({r['kind']}, {r['to_club']} {r['season']}/{str(r['season'] + 1)[2:]}): "
              f"{r['games']} games, {r['removed']} removed, {r['conflicts']} kept by appearance; "
              f"{r['current_share']:.3f} -> {r['fit_share']:.3f}")
    return ex


if __name__ == "__main__":
    main()
